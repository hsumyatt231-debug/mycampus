"""Online-only classrooms, memberships and their audit events."""

from __future__ import annotations

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from models.base import Base, TimestampMixin, utcnow
from utils.validation import MembershipEventType, MembershipStatus


class Classroom(Base, TimestampMixin):
    __tablename__ = "classrooms"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    teacher_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="RESTRICT"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    subject_name: Mapped[str] = mapped_column(String(120), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Generated by the server; clients may never submit one.
    join_code: Mapped[str] = mapped_column(String(32), nullable=False, unique=True)
    timezone: Mapped[str] = mapped_column(String(64), nullable=False)
    archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)


class ClassroomMember(Base):
    __tablename__ = "classroom_members"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    classroom_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("classrooms.id", ondelete="CASCADE"), nullable=False
    )
    student_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False
    )
    student_name: Mapped[str | None] = mapped_column(String(120), nullable=True)
    student_email: Mapped[str | None] = mapped_column(String(255), nullable=True)
    status: Mapped[str] = mapped_column(
        String(16), nullable=False, default=MembershipStatus.active.value
    )
    rejoin_blocked: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    joined_at: Mapped[DateTime | None] = mapped_column(DateTime, nullable=True)
    ended_at: Mapped[DateTime | None] = mapped_column(DateTime, nullable=True)

    __table_args__ = (
        UniqueConstraint("classroom_id", "student_id", name="uq_members_classroom_student"),
        CheckConstraint(
            "status IN ('active', 'left', 'removed')", name="ck_members_status"
        ),
        Index("ix_members_classroom", "classroom_id"),
        Index("ix_members_student", "student_id"),
    )


class MembershipEvent(Base):
    __tablename__ = "membership_events"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    classroom_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("classrooms.id", ondelete="CASCADE"), nullable=False
    )
    membership_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("classroom_members.id", ondelete="CASCADE"), nullable=False
    )
    performed_by: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="RESTRICT"), nullable=False
    )
    event_type: Mapped[str] = mapped_column(String(16), nullable=False)
    student_name: Mapped[str | None] = mapped_column(String(120), nullable=True)
    created_at: Mapped[DateTime] = mapped_column(DateTime, nullable=False, default=utcnow)

    __table_args__ = (
        CheckConstraint(
            "event_type IN ('joined', 'left', 'removed', 'unblocked')",
            name="ck_membership_event_type",
        ),
        Index("ix_membership_events_classroom", "classroom_id", "created_at"),
    )
